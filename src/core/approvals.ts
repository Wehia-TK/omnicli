import { createServer, type Server } from 'node:http'
import { randomBytes } from 'node:crypto'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { ApprovalRequest } from '@shared/types'

/**
 * In-app approvals for Claude Code (the same mechanism Claude Desktop uses): Claude is started with
 * `--permission-prompt-tool mcp__aihub__approve`, and a tiny MCP server forwards each permission prompt
 * to this loopback server, which holds it until you click Allow / Deny in the session view.
 */

type Decision = { behavior: 'allow'; updatedInput: Record<string, unknown> } | { behavior: 'deny'; message: string }

interface Pending extends ApprovalRequest {
  resolve: (d: Decision) => void
}

const pending = new Map<string, Pending>()
const alwaysAllow = new Map<number, Set<string>>()
let server: Server | null = null
let port = 0
const token = randomBytes(24).toString('hex')
let scriptPath = ''
let configDir = ''
let onChange: (req?: ApprovalRequest) => void = () => undefined

const MCP_SCRIPT = String.raw`
// Omni CLI approval bridge — MCP stdio server (newline-delimited JSON-RPC). Generated by Omni CLI.
const http = require('http')
const readline = require('readline')
const PORT = Number(process.env.AIHUB_PORT), TOKEN = process.env.AIHUB_TOKEN, TASK = Number(process.env.AIHUB_TASK)
const send = (msg) => process.stdout.write(JSON.stringify(msg) + '\n')
function ask(args) {
  return new Promise((resolve) => {
    const body = JSON.stringify({ task: TASK, tool_name: args.tool_name, input: args.input || {} })
    const req = http.request({ host: '127.0.0.1', port: PORT, path: '/approve', method: 'POST',
      headers: { 'content-type': 'application/json', 'x-aihub-token': TOKEN, 'content-length': Buffer.byteLength(body) } }, (res) => {
      let out = ''
      res.on('data', (d) => (out += d))
      res.on('end', () => resolve(out || JSON.stringify({ behavior: 'deny', message: 'Omni CLI returned no decision' })))
    })
    req.on('error', (e) => resolve(JSON.stringify({ behavior: 'deny', message: 'Omni CLI is not reachable: ' + e.message })))
    req.setTimeout(0)
    req.end(body)
  })
}
readline.createInterface({ input: process.stdin }).on('line', async (line) => {
  let m
  try { m = JSON.parse(line) } catch { return }
  if (m.method === 'initialize') return send({ jsonrpc: '2.0', id: m.id, result: { protocolVersion: (m.params && m.params.protocolVersion) || '2025-06-18', capabilities: { tools: {} }, serverInfo: { name: 'aihub', version: '1.0.0' } } })
  if (m.method === 'tools/list') return send({ jsonrpc: '2.0', id: m.id, result: { tools: [{ name: 'approve', description: 'Ask the Omni CLI user to approve a tool call', inputSchema: { type: 'object', properties: { tool_name: { type: 'string' }, input: { type: 'object' }, tool_use_id: { type: 'string' } }, required: ['tool_name', 'input'] } }] } })
  if (m.method === 'tools/call') {
    const text = await ask((m.params && m.params.arguments) || {})
    return send({ jsonrpc: '2.0', id: m.id, result: { content: [{ type: 'text', text }] } })
  }
  if (m.method === 'ping') return send({ jsonrpc: '2.0', id: m.id, result: {} })
  if (m.id !== undefined) send({ jsonrpc: '2.0', id: m.id, error: { code: -32601, message: 'Method not found' } })
})
`

function summarize(tool: string, input: Record<string, unknown>): string {
  if (typeof input.command === 'string') return `$ ${input.command}`
  if (typeof input.file_path === 'string') return `${tool} ${input.file_path}`
  if (typeof input.url === 'string') return `${tool} ${input.url}`
  if (typeof input.pattern === 'string') return `${tool} ${input.pattern}`
  return tool
}

export function initApprovals(dataDir: string, changed: (req?: ApprovalRequest) => void): void {
  onChange = changed
  configDir = join(dataDir, 'mcp')
  mkdirSync(configDir, { recursive: true })
  scriptPath = join(configDir, 'aihub-approval-mcp.cjs')
  writeFileSync(scriptPath, MCP_SCRIPT, 'utf8')

  server = createServer((req, res) => {
    if (req.method !== 'POST' || req.url !== '/approve' || req.headers['x-aihub-token'] !== token) {
      res.writeHead(403).end()
      return
    }
    let raw = ''
    req.on('data', (d) => {
      raw += d
      if (raw.length > 8 * 1024 * 1024) req.destroy() // a tool call is never this big
    })
    req.on('end', () => {
      let body: { task?: number; tool_name?: string; input?: Record<string, unknown> } = {}
      try {
        body = JSON.parse(raw)
      } catch {
        // ignore
      }
      const taskId = Number(body.task) || 0
      const toolName = String(body.tool_name ?? 'tool')
      const input = body.input ?? {}
      const reply = (d: Decision): void => {
        res.writeHead(200, { 'content-type': 'application/json' }).end(JSON.stringify(d))
      }
      if (alwaysAllow.get(taskId)?.has(toolName)) return reply({ behavior: 'allow', updatedInput: input })
      const id = randomBytes(8).toString('hex')
      const reqInfo: Pending = {
        id,
        taskId,
        toolName,
        input,
        summary: summarize(toolName, input),
        createdAt: new Date().toISOString(),
        resolve: (d) => {
          pending.delete(id)
          reply(d)
          onChange()
        }
      }
      pending.set(id, reqInfo)
      // If Claude gives up (stopped run), drop the request
      res.on('close', () => {
        if (pending.has(id)) {
          pending.delete(id)
          onChange()
        }
      })
      onChange(stripResolve(reqInfo))
    })
  })
  server.requestTimeout = 0
  server.headersTimeout = 60_000
  server.listen(0, '127.0.0.1', () => {
    const a = server!.address()
    port = typeof a === 'object' && a ? a.port : 0
  })
}

const stripResolve = (p: Pending): ApprovalRequest => {
  const { resolve: _r, ...rest } = p
  void _r
  return rest
}

/** Writes the per-task MCP config Claude loads with --mcp-config. Returns null if the bridge isn't running. */
export function approvalMcpConfig(taskId: number): string | null {
  if (!port || !scriptPath) return null
  const file = join(configDir, `task-${taskId}.json`)
  writeFileSync(
    file,
    JSON.stringify({
      mcpServers: {
        aihub: {
          type: 'stdio',
          command: process.execPath,
          args: [scriptPath],
          env: { ELECTRON_RUN_AS_NODE: '1', AIHUB_PORT: String(port), AIHUB_TOKEN: token, AIHUB_TASK: String(taskId) }
        }
      }
    }),
    'utf8'
  )
  return file
}

/** Deny everything still waiting for a task (called when the run is stopped). */
export function cancelApprovals(taskId: number): void {
  for (const p of [...pending.values()]) if (p.taskId === taskId) p.resolve({ behavior: 'deny', message: 'The run was stopped' })
  alwaysAllow.delete(taskId)
}

export const approvals = {
  list: (taskId?: number): ApprovalRequest[] => [...pending.values()].filter((p) => !taskId || p.taskId === taskId).map(stripResolve),

  decide: (id: string, decision: 'allow' | 'always' | 'deny', message?: string): true => {
    const p = pending.get(id)
    if (!p) throw new Error('That request is no longer waiting')
    if (decision === 'deny') {
      p.resolve({ behavior: 'deny', message: message?.trim() || 'The user denied this action in Omni CLI' })
    } else {
      if (decision === 'always') {
        const set = alwaysAllow.get(p.taskId) ?? new Set<string>()
        set.add(p.toolName)
        alwaysAllow.set(p.taskId, set)
      }
      p.resolve({ behavior: 'allow', updatedInput: p.input })
    }
    return true
  }
}
